import { run_shardable_test, } from '../test-harness';

run_shardable_test([
  "det([[2,-(2),3],[1,-(1),-(2)],[-(3),1,5]])",
  "-14",

  "det([[(0+0),-(8),10],[3,4,1],[8,1,8]])",
  "-162",

  "det([[(0+0),(0+0),1],[1,(0+0),1],[(0+0),1,(0+0)]])",
  "1",

  "det([[(0+0),-(7),10],[3,-(2),1],[8,1,8]])",
  "302",

  "det([[1,-(1),1],[-(2),2,-(3)],[4,-(5),9]])",
  "-1",

  "det([[2,-(2),19],[1,-(1),-(8)],[-(3),1,17]])",
  "-70",

  "det([[(0+0),-(8),-(7)],[3,4,-(2)],[8,1,1]])",
  "355",

  "det([[(0+0),-(8)],[3,4]])",
  "24",

  "det([[(0+0),-(7)],[3,-(2)]])",
  "21",

  // 1x1
  "det([[7]])",
  "7",

  "det([[a]])",
  "a",

  // not a square matrix: left unevaluated
  "det(a)",
  "det(a)",

  "det([[1,2,3],[4,5,6]])",
  "det([[1,2,3],[4,5,6]])",

  "det([1,2,3])",
  "det([1,2,3])",

  // singular
  "det([[1,2,3],[4,5,6],[7,8,9]])",
  "0",

  "det(zero(3,3))",
  "0",

  "det(unit(4))",
  "1",

  // needs a row swap: the sign flips
  "det([[0,1],[1,0]])",
  "-1",

  "det([[a,b],[c,d]])",
  "a*d-b*c",

  // cofactor expansion along the first row, e renamed to e1
  "det([[a,b,c],[d,e1,f],[g,h,k]])",
  "a*e1*k-a*f*h-b*d*k+b*f*g+c*d*h-c*e1*g",

  "det([[x,1],[1,x]])",
  "x^2-1",

  "det([[1,2,3,4],[5,6,7,8],[2,6,4,8],[3,1,1,2]])",
  "72",

  "det([[2,3,-2,5],[6,-2,1,4],[5,10,3,-2],[-1,2,2,3]])",
  "-1629",

  // 1/2*1/5-1/3*1/4
  "det([[1/2,1/3],[1/4,1/5]])",
  "1/60",

  "det(hilbert(3))",
  "1/2160",

  "det([[1.5,2],[3,5]])",
  "1.5",

  // i*i-1
  "det([[i,1],[1,i]])",
  "-2",
])
